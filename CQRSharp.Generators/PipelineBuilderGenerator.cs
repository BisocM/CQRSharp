using System;
using System.Linq;
using System.Text;
using CQRSharp.Shared.Constants;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace CQRSharp.Generators
{
    [Generator]
    public class PipelineBuilderGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            // Post-initialization output
            context.RegisterPostInitializationOutput(ctx =>
            {
                ctx.AddSource(
                    "PipelineBuilder_Init.g.cs",
                    SourceText.From("//<auto-generated/> //PipelineBuilder initialized", Encoding.UTF8));
            });

            // 1) Create syntax provider to find classes/records implementing IRequest
            var requestSymbolsProvider = context.SyntaxProvider
                .CreateSyntaxProvider(
                    predicate: static (node, _) =>
                        node is ClassDeclarationSyntax or RecordDeclarationSyntax,
                    transform: static (ctx, cancellationToken) =>
                    {
                        var symbol = ctx.SemanticModel.GetDeclaredSymbol(ctx.Node, cancellationToken);
                        return symbol as INamedTypeSymbol; // We'll do the interface check later
                    })
                // Filter out nulls
                .Where(symbol => symbol is not null)
                // Collect them all into an array
                .Collect();

            // 2) Combine the (collected) symbols array with the Compilation
            var compilationAndSymbols = requestSymbolsProvider.Combine(context.CompilationProvider);

            // 3) Register the final source output on that combined provider
            context.RegisterSourceOutput(compilationAndSymbols, (spc, source) =>
            {
                try
                {
                    // "source" is a ValueTuple of (ImmutableArray<INamedTypeSymbol> collectedSymbols, Compilation compilation)
                    var (collectedSymbols, compilation) = source;

                    // If none, emit a warning
                    if (collectedSymbols.Length == 0)
                    {
                        ReportDiagnostic(
                            spc,
                            "CQRGEN1001",
                            "No classes or records found. Nothing to generate.",
                            DiagnosticSeverity.Warning);
                        return;
                    }

                    // Retrieve known interface symbols
                    var iRequestSymbol = compilation.GetTypeByMetadataName("CQRSharp.Interfaces.Markers.Request.IRequest");
                    var iQuerySymbol   = compilation.GetTypeByMetadataName("CQRSharp.Interfaces.Markers.Query.IQuery`1");
                    var iCommandSymbol = compilation.GetTypeByMetadataName("CQRSharp.Interfaces.Markers.Command.ICommand");

                    if (iRequestSymbol is null)
                    {
                        // If we can't find IRequest, no point in generating
                        ReportDiagnostic(
                            spc,
                            "CQRGEN1003",
                            "Could not locate CQRSharp.Interfaces.Markers.Request.IRequest in the compilation.",
                            DiagnosticSeverity.Warning);
                        return;
                    }

                    // Now filter only those symbols that actually implement IRequest
                    var requestImplementors = collectedSymbols
                        .Where(s => s!.AllInterfaces.Any(i =>
                            SymbolEqualityComparer.Default.Equals(i, iRequestSymbol)))
                        .ToArray();

                    if (requestImplementors.Length == 0)
                    {
                        ReportDiagnostic(spc, "CQRGEN1001", "No IRequest implementations found.", DiagnosticSeverity.Warning);
                        return;
                    }

                    // Build the generation string
                    var sb = new StringBuilder();
                    sb.AppendLine("//<auto-generated/>");
                    sb.AppendLine("using System;");
                    sb.AppendLine("using System.Collections.Generic;");
                    sb.AppendLine("using System.Linq;");
                    sb.AppendLine("using System.Threading;");
                    sb.AppendLine("using System.Threading.Tasks;");
                    sb.AppendLine("using CQRSharp.Core.Pipelines;");
                    sb.AppendLine("using CQRSharp.Data.Commands;");
                    sb.AppendLine("using CQRSharp.Core.Caching.Pipelines;");
                    sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
                    sb.AppendLine();
                    sb.AppendLine($"namespace {SourceGeneratorConstants.GeneratedNamespace}");
                    sb.AppendLine("{");
                    sb.AppendLine($"    public static class {SourceGeneratorConstants.PipelineRegistryClassName}");
                    sb.AppendLine("    {");
                    sb.AppendLine($"        public static IReadOnlyDictionary<Type, PipelineBuilderDelegate> {SourceGeneratorConstants.PipelineMapPropertyName} {{ get; }} =");
                    sb.AppendLine("            new Dictionary<Type, PipelineBuilderDelegate>");
                    sb.AppendLine("            {");

                    foreach (var symbol in requestImplementors)
                    {
                        try
                        {
                            var requestType = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

                            // Check if this request implements IQuery<T>
                            // If found, use T from IQuery<T>. 
                            // Otherwise, check if it implements ICommand => CommandResult
                            // If it implements neither (should not happen if it's truly an IRequest?), fallback to CommandResult or something else.
                            var foundIQuery = symbol.AllInterfaces.FirstOrDefault(i =>
                                iQuerySymbol is not null
                                && i.IsGenericType
                                && SymbolEqualityComparer.Default.Equals(i.OriginalDefinition, iQuerySymbol));

                            string resultType;
                            if (foundIQuery is { TypeArguments.Length: 1 })
                            {
                                // It's a query, so use T from IQuery<T>
                                resultType = foundIQuery.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                            }
                            else if (iCommandSymbol is not null
                                     && symbol.AllInterfaces.Any(i => SymbolEqualityComparer.Default.Equals(i, iCommandSymbol)))
                            {
                                // It's a command, so default to CommandResult
                                resultType = "global::CQRSharp.Data.Commands.CommandResult";
                            }
                            else
                            {
                                // Fallback for anything else that is an IRequest but not a known query/command
                                // Adjust if you have other request patterns
                                resultType = "global::System.Object";
                            }

                            sb.AppendLine("                {");
                            sb.AppendLine($"                    typeof({requestType}),");
                            sb.AppendLine("                    (services, request, finalHandler, ct) =>");
                            sb.AppendLine("                    {");
                            sb.AppendLine($"                        //Resolve all pipeline behaviors for {requestType}");
                            sb.AppendLine($"                        var behaviors = services.GetServices(typeof(IPipelineBehavior<{requestType}, {resultType}>))");
                            sb.AppendLine($"                            .Cast<IPipelineBehavior<{requestType}, {resultType}>>().ToArray();");
                            sb.AppendLine();
                            sb.AppendLine($"                        Func<{requestType}, CancellationToken, Task<{resultType}>> pipeline = async (req, cancellationToken) =>");
                            sb.AppendLine("                        {");
                            sb.AppendLine("                            // Final delegate: invoke the finalHandler as an object-based lambda");
                            sb.AppendLine($"                            return await Task.FromResult(({resultType})await ((Func<CancellationToken, Task<object>>)(finalHandler))(cancellationToken));");
                            sb.AppendLine("                        };");
                            sb.AppendLine();
                            sb.AppendLine("                        // Chain pipeline behaviors in reverse order");
                            sb.AppendLine("                        for (int i = behaviors.Length - 1; i >= 0; i--)");
                            sb.AppendLine("                        {");
                            sb.AppendLine("                            var behavior = behaviors[i];");
                            sb.AppendLine("                            var next = pipeline;");
                            sb.AppendLine($"                            pipeline = (req, cancellationToken) => behavior.Handle(req, ctInner => next(req, ctInner), cancellationToken);");
                            sb.AppendLine("                        }");
                            sb.AppendLine();
                            sb.AppendLine($"                        return pipeline(({requestType})request, ct).ContinueWith(t => (object)t.Result, ct);");
                            sb.AppendLine("                    }");
                            sb.AppendLine("                },");
                        }
                        catch (Exception ex)
                        {
                            ReportDiagnostic(
                                spc,
                                "CQRGEN1002",
                                $"Error processing request type {symbol?.ToDisplayString()}: {ex.Message}",
                                DiagnosticSeverity.Error);
                        }
                    }

                    sb.AppendLine("            };");
                    sb.AppendLine("    }");
                    sb.AppendLine("}");

                    spc.AddSource(
                        "PipelineBuilders.g.cs",
                        SourceText.From(sb.ToString(), Encoding.UTF8));

                    // Let the user know we succeeded
                    ReportDiagnostic(
                        spc,
                        "CQRGEN1000",
                        "PipelineBuilderGenerator completed successfully.",
                        DiagnosticSeverity.Info);
                }
                catch (Exception ex)
                {
                    ReportDiagnostic(
                        spc,
                        "CQRGEN9999",
                        $"Fatal error in PipelineBuilderGenerator: {ex.Message}",
                        DiagnosticSeverity.Error);
                }
            });
        }

        private static void ReportDiagnostic(SourceProductionContext spc, string id, string message, DiagnosticSeverity severity)
        {
            var descriptor = new DiagnosticDescriptor(
                id,
                "CQRSharp Generator Diagnostic",
                message,
                "SourceGenerator",
                severity,
                true);

            spc.ReportDiagnostic(Diagnostic.Create(descriptor, Location.None));
        }
    }
}